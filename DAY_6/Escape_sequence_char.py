#sequence of characters after backslash "\" are called escape sequence characters.

print("Hello\nWorld")      # \n  New line       | Output: Hello (newline) World
print("Hello\tWorld")      # \t  Tab space       | Output: Hello   World
print("She said \"Hi\"")   # \"  Double quote    | Output: She said "Hi"
print('It\'s fine')        # \'  Single quote    | Output: It's fine
print("C:\\Users\\Guest")  # \\  Backslash       | Output: C:\Users\Guest   