# Assignment (=)
name = "Kumar"
print(name)  


# Add and assign (+=)
score = 10
score += 5
print(score)  


# Subtract and assign (-=)
balance = 100
balance -= 20
print(balance)  


# Multiply and assign (*=)
quantity = 4
quantity *= 3
print(quantity)  


# Divide and assign (/=)
total_price = 100
total_price /= 4
print(total_price)  


# Floor-divide and assign (//=)
students = 25
groups = 4
students //= groups
print(students) 


# Remainder and assign (%=)
number = 17
number %= 5
print(number) 


# Power and assign (**=)
number = 2
number **= 3
print(number)  


# Bitwise AND and assign (&=)
number = 11
number &= 5
print(number)  


# Bitwise OR and assign (|=)
number = 11
number |= 5
print(number)  


# Bitwise XOR and assign (^=)
number = 11
number ^= 5
print(number)  

# Right-shift and assign (>>=)
number = 11
number >>= 1
print(number)  


# Left-shift and assign (<<=)
number = 11
number <<= 1
print(number)  