#A list is an ordered, mutable collection of different datatype written inside square brackets '[]'
elements=["book",False,100,"rakesh"]
print(elements)         #['book', False, 100, 'rakesh']



"""List Indexing--
Indexing means accessing an element using its position
indexing starts from 0,"""

numbers = [10, 20, 30, 40, 50]

print(numbers[0])           #10
print(numbers[2])           #30
print(numbers[4])           #50

#negative indexing
print(numbers[-4])          #20



#changing list element
numbers = [10, 20, 30, 40]

numbers[1] = 200

print(numbers)              #[10, 200, 30, 40]









